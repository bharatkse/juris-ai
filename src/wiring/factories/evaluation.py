"""
RAG evaluation composition.

Builds the LLM judge shared by RAGEvaluator (answer_relevancy /
context_precision / context_recall) and by whichever FaithfulnessBackend
is selected, plus the single switch point deciding which
FaithfulnessBackend implementation FaithfulnessMetric and
OnlineEvalSampler both get -- see build_faithfulness_backend.

The resolver is only constructed when the judge is actually invoked,
not eagerly at build time -- callers that never produce a metric
result requiring a judge call (e.g. evaluation cases with no generated
answer) never need a configured LLM provider.
"""

from __future__ import annotations

import hashlib
from typing import TYPE_CHECKING

from adapters.observability.metrics import metrics
from core.dto.clients.llm import LLMMessageDTO, LLMRequestDTO
from core.dto.inference import LLMInferenceConfig
from core.enums import MessageRoleEnum
from rag.evaluation.evaluator import Judge, RAGEvaluator
from rag.evaluation.faithfulness_backend import (
    FaithfulnessBackend,
    LegacyFaithfulnessBackend,
    RagasFaithfulnessBackend,
)
from wiring.factories.llm_resolver import build_llm_resolver

if TYPE_CHECKING:
    from adapters.cache.base import AbstractCache
    from config.settings import Settings

_JUDGE_CACHE_KEY_VERSION = "v1"


def build_llm_judge(*, settings: Settings, cache: AbstractCache) -> Judge:
    """
    Build a Judge callable backed by the default configured LLM
    provider, memoized against cache.

    Every judge call (faithfulness, answer relevancy, context
    precision/recall -- legacy and ragas-backed alike, see
    ragas_llm_adapter.py) is already pinned to temperature=0.0 (see
    below), making it deterministic-in-practice -- a safe, high-value
    cache candidate. Not a mathematical guarantee (provider-side
    floating-point/batching effects could in principle still vary a
    temp=0 response), stated rather than hidden.

    The cache key includes provider+model, not just the prompt --
    deliberately, so that routing judge calls to a different model
    later (see scripts/python/calibrate_answer_quality_thresholds.py's
    model-comparison runs) can never silently serve a stale response
    generated by a different model under the same key.
    """

    async def judge(prompt: str) -> str:
        resolver = build_llm_resolver(settings=settings)
        client = resolver.get()

        # settings.llm.JUDGE_MODEL, not client.model (the default
        # GROQ_MODEL agent reasoning uses) -- validated empirically
        # (see JUDGE_MODEL's own docstring in config/llm.py) to hold
        # the same groundedness separation quality at a fraction of
        # the cost. This is the ACTUAL model the request below uses
        # (inference.model overrides the client's default), so the
        # cache key must reflect it, not client.model -- otherwise a
        # judge-model change would silently share (or shadow) cache
        # entries with whatever model generated them.
        judge_model = settings.llm.JUDGE_MODEL.value

        cache_key = (
            f"jurisai:cache:judge:{_JUDGE_CACHE_KEY_VERSION}:"
            f"{client.provider}:{judge_model}:"
            f"{hashlib.sha256(prompt.encode('utf-8')).hexdigest()}"
        )

        cached = await cache.get(cache_key)

        if cached is not None:
            metrics.record_cache_request(result="hit", cache="judge")
            return cached

        metrics.record_cache_request(result="miss", cache="judge")

        response = await client.generate(
            request=LLMRequestDTO(
                messages=(
                    LLMMessageDTO(
                        role=MessageRoleEnum.USER,
                        content=prompt,
                    ),
                ),
                # Every caller of this judge (faithfulness, answer
                # relevancy, context precision/recall -- legacy and
                # ragas-backed alike, see ragas_llm_adapter.py) is a
                # scoring call, not a generative one. Previously this
                # request carried no inference config, silently
                # defaulting to LLMInferenceConfig's bare 0.2 -- an
                # ambient, undeliberate temperature for a judge whose
                # output is supposed to be a reproducible score.
                # Pinned to 0.0 (as close to deterministic as providers
                # allow) so repeated judge calls on the same input are
                # stable -- required for the empirical threshold
                # calibration in AnswerQualityPolicy to remain
                # meaningful over time (scripts/python/
                # calibrate_answer_quality_thresholds.py).
                inference=LLMInferenceConfig(temperature=0.0, model=judge_model),
            ),
        )

        await cache.set(
            cache_key,
            response.content,
            ttl=settings.security.CACHE_TTL_SECONDS,
        )

        return response.content

    return judge


def build_rag_evaluator(*, settings: Settings, cache: AbstractCache) -> RAGEvaluator:
    """
    Build a RAGEvaluator backed by the default configured LLM provider.
    """

    return RAGEvaluator(judge=build_llm_judge(settings=settings, cache=cache))


def build_faithfulness_backend(
    *,
    settings: Settings,
    cache: AbstractCache,
) -> FaithfulnessBackend:
    """
    Build the FaithfulnessBackend selected by
    settings.llm.faithfulness_backend.

    This is the single switch point: FaithfulnessMetric and
    OnlineEvalSampler both call this rather than constructing a backend
    or branching on the setting themselves, so changing the setting
    changes behavior for both, by construction.
    """

    judge = build_llm_judge(settings=settings, cache=cache)

    if settings.llm.faithfulness_backend == "ragas":
        return RagasFaithfulnessBackend(judge=judge)

    return LegacyFaithfulnessBackend(evaluator=RAGEvaluator(judge=judge))
