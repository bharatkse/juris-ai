"""
RAG evaluation case models.

Defines the provider-independent input required to evaluate a RAG
response.

The evaluation case preserves the actual output of the frozen RAG
retrieval pipeline rather than reducing retrieval results to plain
text.

The model supports both:

    - retrieval evaluation using expected sources/evidence
    - answer evaluation using reference answer/contexts

The model does not depend on any concrete LLM provider or evaluation
framework.
"""

from __future__ import annotations

from dataclasses import dataclass, field

from rag.models import RetrievalResult


@dataclass(frozen=True, slots=True)
class EvaluationCase:
    """
    Input to a RAG evaluation run.

    Attributes:
        query:
            Original user query.

        answer:
            Answer generated by the RAG pipeline.

        retrieval_results:
            Results returned by the frozen RAG retrieval pipeline.

            Each RetrievalResult contains:

                - retrieved chunk
                - retrieval score
                - embedding representations

            Keeping the complete RetrievalResult allows evaluation to
            inspect retrieval quality and compare embedding
            representations without changing the RAG retrieval
            workflow.

        expected_sources:
            Source identifiers expected to contain relevant evidence
            for the query.

            These are used as retrieval ground truth and are preferred
            over exact chunk IDs because chunk IDs may change when the
            corpus is re-chunked.

        expected_evidence:
            Stable evidence text representing the relevant legal
            evidence expected to be retrieved for the query.

            This is used as retrieval ground truth without depending
            on unstable chunk identifiers.

        reference_answer:
            Optional expected answer used by evaluations that require
            answer ground truth.

        reference_contexts:
            Optional expected/relevant context text used by evaluations
            that require ground-truth retrieval information.
    """

    query: str
    answer: str

    retrieval_results: list[RetrievalResult] = field(
        default_factory=list,
    )

    expected_sources: list[str] = field(
        default_factory=list,
    )

    expected_evidence: list[str] = field(
        default_factory=list,
    )

    reference_answer: str | None = None

    reference_contexts: list[str] | None = None

    @property
    def contexts(self) -> list[str]:
        """
        Return retrieved context text from the RAG retrieval results.

        This provides the plain-text context required by evaluation
        metrics while preserving the complete RetrievalResult objects
        for metrics that need retrieval scores or embedding metadata.
        """

        return [result.chunk.text for result in self.retrieval_results]
