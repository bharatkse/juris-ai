/**
 * Browser-safe configuration. Never put BACKEND_API_URL or secrets here.
 */
import { z } from "zod";

const backend = z.enum(["local", "http"]).optional();

const clientEnvSchema = z.object({
  NEXT_PUBLIC_CHAT_STREAMING: z.string().optional(),
  NEXT_PUBLIC_DEFAULT_THEME: z.enum(["light", "dark"]).optional(),
  NEXT_PUBLIC_FEATURE_CONVERSATION_RENAME: z.string().optional(),
  NEXT_PUBLIC_FEATURE_MEMORY_BACKEND: backend,
  NEXT_PUBLIC_FEATURE_PROJECTS_BACKEND: backend,
  NEXT_PUBLIC_FEATURE_PINS_BACKEND: backend,
  NEXT_PUBLIC_FEATURE_DOCUMENTS_BACKEND: backend,
  NEXT_PUBLIC_FEATURE_PREFERENCES_BACKEND: backend,
  NEXT_PUBLIC_FEATURE_NOTIFICATIONS_BACKEND: backend,
  NEXT_PUBLIC_FEATURE_INTEGRATIONS_BACKEND: backend,
  NEXT_PUBLIC_FEATURE_API_KEYS_BACKEND: backend,
  NEXT_PUBLIC_FEATURE_CONVERSATION_TITLES_BACKEND: backend,
  NEXT_PUBLIC_FEATURE_ADMIN: z.string().optional(),
  NEXT_PUBLIC_FEATURE_PERMISSIONS: z.string().optional(),
});

export type ClientEnv = z.infer<typeof clientEnvSchema>;

export function parseClientEnv(
  source: Record<string, string | undefined> = {
    NEXT_PUBLIC_CHAT_STREAMING: process.env.NEXT_PUBLIC_CHAT_STREAMING,
    NEXT_PUBLIC_DEFAULT_THEME: process.env.NEXT_PUBLIC_DEFAULT_THEME,
    NEXT_PUBLIC_FEATURE_CONVERSATION_RENAME:
      process.env.NEXT_PUBLIC_FEATURE_CONVERSATION_RENAME,
    NEXT_PUBLIC_FEATURE_MEMORY_BACKEND:
      process.env.NEXT_PUBLIC_FEATURE_MEMORY_BACKEND,
    NEXT_PUBLIC_FEATURE_PROJECTS_BACKEND:
      process.env.NEXT_PUBLIC_FEATURE_PROJECTS_BACKEND,
    NEXT_PUBLIC_FEATURE_PINS_BACKEND: process.env.NEXT_PUBLIC_FEATURE_PINS_BACKEND,
    NEXT_PUBLIC_FEATURE_DOCUMENTS_BACKEND:
      process.env.NEXT_PUBLIC_FEATURE_DOCUMENTS_BACKEND,
    NEXT_PUBLIC_FEATURE_PREFERENCES_BACKEND:
      process.env.NEXT_PUBLIC_FEATURE_PREFERENCES_BACKEND,
    NEXT_PUBLIC_FEATURE_NOTIFICATIONS_BACKEND:
      process.env.NEXT_PUBLIC_FEATURE_NOTIFICATIONS_BACKEND,
    NEXT_PUBLIC_FEATURE_INTEGRATIONS_BACKEND:
      process.env.NEXT_PUBLIC_FEATURE_INTEGRATIONS_BACKEND,
    NEXT_PUBLIC_FEATURE_API_KEYS_BACKEND:
      process.env.NEXT_PUBLIC_FEATURE_API_KEYS_BACKEND,
    NEXT_PUBLIC_FEATURE_CONVERSATION_TITLES_BACKEND:
      process.env.NEXT_PUBLIC_FEATURE_CONVERSATION_TITLES_BACKEND,
    NEXT_PUBLIC_FEATURE_ADMIN: process.env.NEXT_PUBLIC_FEATURE_ADMIN,
    NEXT_PUBLIC_FEATURE_PERMISSIONS: process.env.NEXT_PUBLIC_FEATURE_PERMISSIONS,
  },
): ClientEnv {
  return clientEnvSchema.parse(source);
}

export function isChatStreamingEnabled(
  value = process.env.NEXT_PUBLIC_CHAT_STREAMING,
): boolean {
  return value?.trim().toLowerCase() !== "false";
}
